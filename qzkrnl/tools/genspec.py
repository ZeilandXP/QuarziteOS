#!/usr/bin/env python3
#
# PROJECT:     QuarziteOS Kernel (qzkrnl)
# LICENSE:     GPL-2.0-or-later (https://spdx.org/licenses/GPL-2.0-or-later)
# PURPOSE:     Generate qzkrnl.spec: the full NTOSKRNL export surface, where
#              everything qzkrnl does not implement yet becomes a stub.
#
# Why: FreeLoader binds the imports of HAL.DLL, KDCOM.DLL, BOOTVID.DLL and
# every boot driver against the kernel image (registered as "ntoskrnl.exe").
# If a single imported name is missing, the boot fails. By exporting the same
# name set as ntoskrnl.exe -- implemented functions from exports.spec, stubs
# for the rest -- qzkrnl can be loaded by the unmodified boot chain, and every
# stub that gets called reports exactly which export needs implementing next.
#
# Usage:  python3 qzkrnl/tools/genspec.py         (from the source root)
#
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
NTOS_SPEC = os.path.join(ROOT, "ntoskrnl", "ntoskrnl.spec")
QZ_DIR = os.path.join(ROOT, "qzkrnl")
IMPL_SPEC = os.path.join(QZ_DIR, "exports.spec")
OUT_SPEC = os.path.join(QZ_DIR, "qzkrnl.spec")
OUT_HDR = os.path.join(QZ_DIR, "include", "exportstats.h")

# "@ <callconv> [-opt ...] Name[(args)] [target]"
LINE_RE = re.compile(r"^@\s+(\S+)\s+((?:-\S+\s+)*)([^\s(]+)")


def parse(path):
    entries = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.split("#", 1)[0].rstrip()
            m = LINE_RE.match(line)
            if not m:
                continue
            callconv, opts, name = m.group(1), m.group(2).split(), m.group(3)
            entries.append((callconv, opts, name, line))
    return entries


def main():
    ntos = parse(NTOS_SPEC)
    impl = parse(IMPL_SPEC)
    impl_names = {e[2] for e in impl}

    # Only keep the options that select *whether* an export exists;
    # signature-related flags are meaningless for a stub.
    keep = ("-arch=", "-version=")

    out = []
    out.append("#")
    out.append("# AUTOGENERATED by qzkrnl/tools/genspec.py -- DO NOT EDIT.")
    out.append("# Edit qzkrnl/exports.spec instead, then re-run the script.")
    out.append("#")
    out.append("")
    out.append("# ---- Implemented by qzkrnl (from exports.spec) ----")
    with open(IMPL_SPEC, encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("@"):
                out.append(raw.rstrip())
    out.append("")
    out.append("# ---- Not implemented yet: stubs matching ntoskrnl.exe ----")

    stub_funcs = stub_data = 0
    seen = set(impl_names)
    for callconv, opts, name, _ in ntos:
        if name in seen:
            continue
        seen.add(name)
        flags = " ".join(o for o in opts if o.startswith(keep))
        flags = (flags + " ") if flags else ""
        if callconv == "extern":
            # All unimplemented data exports alias one zero-filled block.
            out.append(f"@ extern {flags}{name} QzUnimplementedData")
            stub_data += 1
        else:
            out.append(f"@ stub {flags}{name}")
            stub_funcs += 1

    missing = sorted(impl_names - {e[2] for e in ntos})

    with open(OUT_SPEC, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    with open(OUT_HDR, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* AUTOGENERATED by qzkrnl/tools/genspec.py -- DO NOT EDIT. */\n")
        f.write("#pragma once\n")
        f.write(f"#define QZ_EXPORTS_IMPLEMENTED {len(impl_names)}\n")
        f.write(f"#define QZ_EXPORTS_STUB_FUNCS  {stub_funcs}\n")
        f.write(f"#define QZ_EXPORTS_STUB_DATA   {stub_data}\n")

    print(f"qzkrnl.spec: {len(impl_names)} implemented, "
          f"{stub_funcs} function stubs, {stub_data} data stubs")
    if missing:
        print("note: exported by qzkrnl but not by ntoskrnl:", ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
