#!/usr/bin/env python3
#
# PROJECT:     QuarziteOS Kernel (qzkrnl)
# LICENSE:     GPL-2.0-or-later (https://spdx.org/licenses/GPL-2.0-or-later)
# PURPOSE:     Generate include/systable.h: the system service table.
#
# ntdll.dll's system call stubs number the services in the order of
# ntoskrnl/include/sysfuncs.h (the NT5 block; the ntdll on the boot media is
# built with SYSFUNCS_NT5_ONLY). qzkrnl's dispatcher must use the very same
# numbering. Each service is bound to the function qzkrnl implements for it:
# Nt<Name> if there is one (it honours PreviousMode), else Zw<Name> (a
# kernel-side implementation, called with the user's arguments). Services
# with neither fail with STATUS_NOT_IMPLEMENTED and are reported by name.
#
# Usage:  python3 qzkrnl/tools/gensys.py      (genspec.py runs it too)
#
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SYSFUNCS = os.path.join(ROOT, "ntoskrnl", "include", "sysfuncs.h")
QZ_DIR = os.path.join(ROOT, "qzkrnl")
OUT = os.path.join(QZ_DIR, "include", "systable.h")

SVC_RE = re.compile(r"^\s*SVC_\((\w+),\s*(\d+)\)")
# A function definition in qzkrnl's style: the name at the start of a line
DEF_RE = re.compile(r"^(Nt|Zw)(\w+)\s*\(")
ONE_LINE_RE = re.compile(r"^NTSTATUS\s+NTAPI\s+(Nt|Zw)(\w+)\s*\(")


def services():
    result = []
    with open(SYSFUNCS, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#endif") and "NT6_ONLY" in line:
                break   # the end of the NT5 block
            m = SVC_RE.match(line)
            if m:
                result.append((m.group(1), int(m.group(2))))
    return result


def implemented():
    found = {"Nt": set(), "Zw": set()}
    for top, _dirs, files in os.walk(QZ_DIR):
        if os.sep + "tools" in top:
            continue
        for name in files:
            if not name.endswith(".c"):
                continue
            prev = ""
            with open(os.path.join(top, name), encoding="utf-8", errors="replace") as f:
                for line in f:
                    one = ONE_LINE_RE.match(line)
                    if one:
                        found[one.group(1)].add(one.group(2))
                    m = DEF_RE.match(line)
                    # a definition, not a call: the previous line is the calling
                    # convention (NTAPI) or the return type
                    if m and prev.strip() in ("NTAPI", "NTSTATUS", "NTSTATUS NTAPI"):
                        found[m.group(1)].add(m.group(2))
                    prev = line
    return found


def main():
    svcs = services()
    impl = implemented()
    lines = [
        "/* Generated by qzkrnl/tools/gensys.py from ntoskrnl/include/sysfuncs.h -- do not edit */",
        "",
        f"#define QZ_SERVICE_COUNT {len(svcs)}",
        "",
    ]
    count_nt = count_zw = 0
    for index, (name, args) in enumerate(svcs):
        lines.append(f"#define QZ_SVCNUM_{name} {index}")
    lines.append("")
    lines.append("/* QZ_SVC_IMPL(Name, ArgumentDwords, Symbol, ViaZw), QZ_SVC_NONE(Name, ArgumentDwords) */")
    lines.append("#ifdef QZ_SVC_IMPL")
    for name, args in svcs:
        if name in impl["Nt"]:
            lines.append(f'QZ_SVC_IMPL({name}, {args}, "_Nt{name}@{args * 4}", 0)')
            count_nt += 1
        elif name in impl["Zw"]:
            lines.append(f'QZ_SVC_IMPL({name}, {args}, "_Zw{name}@{args * 4}", 1)')
            count_zw += 1
        else:
            lines.append(f"QZ_SVC_NONE({name}, {args})")
    lines.append("#endif")
    lines.insert(3, f"#define QZ_SERVICES_IMPLEMENTED {count_nt + count_zw}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"systable.h: {len(svcs)} services, {count_nt} Nt + {count_zw} Zw implemented")


if __name__ == "__main__":
    main()
