static VOID
QzIoPrintDeviceName(PDEVICE_OBJECT Device)
{
    union { OBJECT_NAME_INFORMATION Info; UCHAR Raw[256]; } Name;
    ULONG Length;

    if (NT_SUCCESS(ObQueryNameString(Device, &Name.Info, sizeof(Name), &Length)) &&
        Name.Info.Name.Length)
        QzPrint("%-30wZ", &Name.Info.Name);
    else
        QzPrint("(unnamed %p)                ", Device);
}

VOID
QzIoDumpDevices(VOID)
{
    PLIST_ENTRY Entry;

    for (Entry = QzIoDriverList.Flink; Entry != &QzIoDriverList; Entry = Entry->Flink)
    {
        PQZ_DRIVER_EXTENSION Extension = CONTAINING_RECORD(Entry, QZ_DRIVER_EXTENSION, Link);
        PDEVICE_OBJECT Device;

        for (Device = Extension->Public.DriverObject->DeviceObject; Device; Device = Device->NextDevice)
        {
            QzPrint("  ");
            QzIoPrintDeviceName(Device);
            QzPrint(" %-20wZ type %02lx stack %u%s%s\n", &Extension->Public.DriverObject->DriverName,
                    Device->DeviceType, Device->StackSize,
                    QzDeviceExtension(Device)->AttachedTo ? " (filter/FDO)" : "",
                    (Device->Vpb && (Device->Vpb->Flags & VPB_MOUNTED)) ? " (mounted)" : "");
        }
    }
    QzPrint("  %lu device object(s)\n", QzIoDeviceCount());
}
